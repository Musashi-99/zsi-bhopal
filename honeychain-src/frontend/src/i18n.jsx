const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(localStorage.getItem('aranya_lang') || 'en');
  const [stateId, setStateState] = useState(localStorage.getItem('aranya_state') || 'ST-WB');
  useEffect(() => { document.documentElement.lang = lang === 'bn' ? 'bn' : lang === 'hi' ? 'hi' : 'en'; }, [lang]);
  const value = useMemo(() => ({
    lang,
    stateId,
    setLang: (id) => { localStorage.setItem('aranya_lang', id); setLangState(id); },
    setStateId: (id) => { localStorage.setItem('aranya_state', id); setStateState(id); },
    t: (key) => STR[lang]?.[key] || STR.en[key] || key,
  }), [lang, stateId]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
